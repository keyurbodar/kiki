import { describe, expect, it } from "vitest";
import { diffCategory, isGeneratedDiff } from "./diff-categories";

describe("diffCategory", () => {
  it("classifies migrations as database", () => {
    expect(diffCategory("db/migrations/0001_init.sql")).toBe("database");
    expect(diffCategory("drizzle/0003_users.sql")).toBe("database");
  });

  it("classifies test files and folders as tests", () => {
    expect(diffCategory("src/cart/cart.test.ts")).toBe("tests");
    expect(diffCategory("tests/checkout.py")).toBe("tests");
    expect(diffCategory("pkg/orders/cursor_test.go")).toBe("tests");
  });

  it("classifies lockfiles, vendored and marked files as generated", () => {
    expect(diffCategory("bun.lock")).toBeUndefined();
    expect(diffCategory("web/pnpm-lock.yaml")).toBe("generated");
    expect(diffCategory("vendor/lib/a.go")).toBe("generated");
    expect(diffCategory("dist/app.min.js")).toBe("generated");
    expect(
      diffCategory(
        "src/api/client.ts",
        "@@ -0,0 +1,2 @@\n+// @generated by the api tool\n+export {};",
      ),
    ).toBe("generated");
  });

  it("leaves ordinary source alone", () => {
    expect(diffCategory("src/checkout/retry.ts")).toBeUndefined();
  });
});

describe("isGeneratedDiff", () => {
  it("only reads the marker when the hunk starts at the top of the file", () => {
    expect(isGeneratedDiff("a.ts", "@@ -40,2 +40,2 @@\n+// @generated\n")).toBe(
      false,
    );
  });
});
