import { Atom } from "effect/reactivity";

export type DiffCategory = "database" | "tests" | "generated";

export const diffCategories: ReadonlyArray<DiffCategory> = [
  "database",
  "tests",
  "generated",
];

export type DiffCategoryTotals = {
  files: number;
  additions: number;
  deletions: number;
};

export type DiffBreakdown = Record<DiffCategory, DiffCategoryTotals>;

export type HiddenDiffCategories = Record<DiffCategory, boolean>;

const lockfiles = new Set([
  "pnpm-lock.yaml",
  "package-lock.json",
  "yarn.lock",
  "Cargo.lock",
  "go.sum",
  "poetry.lock",
  "uv.lock",
  "Gemfile.lock",
  "composer.lock",
  "Podfile.lock",
  "flake.lock",
  "openapi.json",
]);

const drizzleSnapshot = /(?:^|\/)drizzle\/[^/]+\/snapshot\.json$/;

const generatedPath =
  /(?:^|\/)(?:vendor|node_modules|__snapshots__)\/|\.xcodeproj\/|_pb2\.py$|\.(?:min\.js|min\.css|map|pb\.go|snap)$|\.generated\./;

const generatedMarker =
  /@generated|code generated by|do not edit|auto-generated/i;

const databasePath =
  /(?:^|\/)(?:migrations?|schema-migrations)\/|(?:^|\/)drizzle\/(?:[^/]+\.sql|[^/]+\/migration\.sql|meta\/(?:\d+_snapshot|_journal)\.json)$/;

const testsPath =
  /(?:^|\/)(?:__tests__|__fixtures__|__mocks__|tests?|spec|fixtures?|testdata|test-data|testing|e2e|cypress|playwright)\/|(?:^|\/)(?:test_[^/]+|[^/]+_test)\.[^/]+$|\.(?:test|spec|fixture|fixtures)\.[^/]+$|(?:^|\/)(?:fixtures?|[^/]+-fixtures?)\.[^/]+$/;

const isGeneratedPath = (path: string) =>
  lockfiles.has(path.slice(path.lastIndexOf("/") + 1)) ||
  drizzleSnapshot.test(path) ||
  generatedPath.test(path);

const leadingLines = (patch: string) => {
  const hunk = patch.match(/^@@ -\d+(?:,\d+)? \+(\d+)/m);
  if (hunk === null) return patch;
  if (Number(hunk[1]) > 1) return "";
  const end = patch.indexOf("\n", hunk.index ?? 0);
  return end === -1 ? "" : patch.slice(end + 1);
};

export function isGeneratedDiff(path: string, patch?: string): boolean {
  if (isGeneratedPath(path)) return true;
  if (patch === undefined) return false;
  const head = leadingLines(patch);
  let cursor = 0;
  for (let line = 0; line < 10 && cursor !== -1; line += 1) {
    cursor = head.indexOf("\n", cursor + 1);
  }
  return generatedMarker.test(cursor === -1 ? head : head.slice(0, cursor));
}

export function diffCategory(
  path: string,
  patch?: string,
): DiffCategory | undefined {
  if (databasePath.test(path)) return "database";
  if (testsPath.test(path)) return "tests";
  if (isGeneratedDiff(path, patch)) return "generated";
  return undefined;
}

export const hiddenDiffCategoriesAtom = Atom.make<HiddenDiffCategories>({
  database: false,
  tests: false,
  generated: false,
}).pipe(Atom.keepAlive);
