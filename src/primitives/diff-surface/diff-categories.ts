import { Schema } from "effect";
import { KeyValueStore } from "effect/persistence";
import { Atom } from "effect/reactivity";
import type {
  DiffCategoryFlags,
  DiffGroupCategory,
} from "./diff-surface-model";

const databasePath =
  /(?:^|\/)(?:migrations?|schema-migrations)\/|(?:^|\/)drizzle\/(?:[^/]+\.sql|[^/]+\/migration\.sql|meta\/(?:\d+_snapshot|_journal)\.json)$/;
const testsPath =
  /(?:^|\/)(?:__tests__|__fixtures__|__mocks__|tests?|spec|fixtures?|testdata|test-data|testing|e2e|cypress|playwright)\/|(?:^|\/)(?:test_[^/]+|[^/]+_test)\.[^/]+$|\.(?:test|spec|fixture|fixtures)\.[^/]+$|(?:^|\/)(?:fixtures?|[^/]+-fixtures?)\.[^/]+$/;
const generatedFileNames = new Set([
  "pnpm-lock.yaml",
  "package-lock.json",
  "yarn.lock",
  "Cargo.lock",
  "go.sum",
  "poetry.lock",
  "uv.lock",
  "Gemfile.lock",
  "composer.lock",
  "Podfile.lock",
  "flake.lock",
  "openapi.json",
]);
const drizzleSnapshotPath = /(?:^|\/)drizzle\/[^/]+\/snapshot\.json$/;
const generatedPath =
  /(?:^|\/)(?:vendor|node_modules|__snapshots__)\/|\.xcodeproj\/|_pb2\.py$|\.(?:min\.js|min\.css|map|pb\.go|snap)$|\.generated\./;
const generatedMarker =
  /@generated|code generated by|do not edit|auto-generated/i;

const isGeneratedPath = (path: string) =>
  generatedFileNames.has(path.slice(path.lastIndexOf("/") + 1)) ||
  drizzleSnapshotPath.test(path) ||
  generatedPath.test(path);

const leadingContent = (patch: string) => {
  const hunk = patch.match(/^@@ -\d+(?:,\d+)? \+(\d+)/m);
  if (hunk === null) return patch;
  if (Number(hunk[1]) > 1) return "";
  const lineEnd = patch.indexOf("\n", hunk.index ?? 0);
  return lineEnd === -1 ? "" : patch.slice(lineEnd + 1);
};

export function isGeneratedFile(path: string, patch?: string) {
  if (isGeneratedPath(path)) return true;
  if (patch === undefined) return false;
  const content = leadingContent(patch);
  let end = 0;
  for (let line = 0; line < 10 && end !== -1; line += 1)
    end = content.indexOf("\n", end + 1);
  return generatedMarker.test(end === -1 ? content : content.slice(0, end));
}

export function diffCategoryForPath(
  path: string,
  patch?: string,
): DiffGroupCategory | undefined {
  if (databasePath.test(path)) return "database";
  if (testsPath.test(path)) return "tests";
  return isGeneratedFile(path, patch) ? "generated" : undefined;
}

const storage = Atom.runtime(
  KeyValueStore.layerStorage(() => globalThis.localStorage),
);

const preference = (key: string) =>
  Atom.kvs({
    runtime: storage,
    key,
    schema: Schema.Boolean,
    defaultValue: () => true,
  });

const hideDatabaseAtom = preference("capy-web:diff-hide-database");
const collapseTestsAtom = preference("capy-web:diff-collapse-tests");
const hideGeneratedAtom = preference("capy-web:diff-hide-generated");

export const diffExpandedCategoriesAtom = Atom.make<Partial<DiffCategoryFlags>>(
  {},
).pipe(Atom.keepAlive);

export const diffHiddenCategoriesAtom = Atom.writable(
  (get): DiffCategoryFlags => ({
    database: get(hideDatabaseAtom),
    tests: get(collapseTestsAtom),
    generated: get(hideGeneratedAtom),
  }),
  (ctx, next: DiffCategoryFlags) => {
    const current: DiffCategoryFlags = {
      database: ctx.get(hideDatabaseAtom),
      tests: ctx.get(collapseTestsAtom),
      generated: ctx.get(hideGeneratedAtom),
    };
    const expanded = ctx.get(diffExpandedCategoriesAtom);
    ctx.set(
      diffExpandedCategoriesAtom,
      Object.fromEntries(
        Object.entries(expanded).filter(
          ([category]) =>
            current[category as DiffGroupCategory] ===
            next[category as DiffGroupCategory],
        ),
      ),
    );
    ctx.set(hideDatabaseAtom, next.database);
    ctx.set(collapseTestsAtom, next.tests);
    ctx.set(hideGeneratedAtom, next.generated);
  },
);
