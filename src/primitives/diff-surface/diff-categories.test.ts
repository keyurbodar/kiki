import { Atom, AtomRegistry } from "effect/reactivity";
import { afterEach, expect, it } from "vitest";
import {
  diffCategoryForPath,
  diffExpandedCategoriesAtom,
  diffHiddenCategoriesAtom,
  isGeneratedFile,
} from "./diff-categories";

afterEach(() => localStorage.clear());

it("classifies database, test and generated paths", () => {
  expect(diffCategoryForPath("db/migrations/001_init.sql")).toBe("database");
  expect(diffCategoryForPath("drizzle/meta/_journal.json")).toBe("database");
  expect(diffCategoryForPath("src/app.test.ts")).toBe("tests");
  expect(diffCategoryForPath("e2e/login.ts")).toBe("tests");
  expect(diffCategoryForPath("bun.lock")).toBeUndefined();
  expect(diffCategoryForPath("pnpm-lock.yaml")).toBe("generated");
  expect(diffCategoryForPath("dist/app.min.js")).toBe("generated");
  expect(diffCategoryForPath("src/app.ts")).toBeUndefined();
});

it("detects generated markers near the top of the file", () => {
  expect(
    isGeneratedFile(
      "src/api.ts",
      "@@ -0,0 +1,2 @@\n+// Code generated by tool. DO NOT EDIT.\n+export {}\n",
    ),
  ).toBe(true);
  expect(
    isGeneratedFile("src/api.ts", "@@ -40,2 +40,2 @@\n+// do not edit\n"),
  ).toBe(false);
});

it("hides every category by default and clears stale expansions on change", () => {
  const registry = AtomRegistry.make();
  const unmount = registry.mount(diffHiddenCategoriesAtom);
  expect(registry.get(diffHiddenCategoriesAtom)).toEqual({
    database: true,
    tests: true,
    generated: true,
  });
  registry.set(diffExpandedCategoriesAtom, { tests: true, generated: true });
  registry.set(diffHiddenCategoriesAtom, {
    database: true,
    tests: false,
    generated: true,
  });
  expect(registry.get(diffExpandedCategoriesAtom)).toEqual({ generated: true });
  expect(registry.get(diffHiddenCategoriesAtom).tests).toBe(false);
  expect(localStorage.getItem("capy-web:diff-collapse-tests")).toBe("false");
  unmount();
  expect(Atom.isWritable(diffHiddenCategoriesAtom)).toBe(true);
});
